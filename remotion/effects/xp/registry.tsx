/** タイトル系プレビューの共通土台: 実フッテージを暗めに敷いてタイトルを乗せる */
const FootageStage: React.FC<{ children: React.ReactNode; dim?: number }> = ({
  children,
  dim = 0.35,
}) => (
  <AbsoluteFill style={{ background: "#000" }}>
    <Video
      src={staticFile(DEMO_CLIP)}
      muted
      loop
      style={{ width: "100%", height: "100%", objectFit: "cover", opacity: dim }}
    />
    <AbsoluteFill>{children}</AbsoluteFill>
  </AbsoluteFill>
);

/**
 * トランジション系プレビューの共通土台: 実フッテージを from、色相を回した同フッテージを
 * to にして、切り替わりが分かるようにする。transition props契約 {from,to,durationInFrames}。
 */
const TransitionStage: React.FC<{
  Transition: React.FC<{
    from: React.ReactNode;
    to: React.ReactNode;
    durationInFrames: number;
  }>;
  durationInFrames: number;
}> = ({ Transition, durationInFrames }) => (
  <AbsoluteFill style={{ background: "#000" }}>
    <Transition
      durationInFrames={durationInFrames}
      from={
        <Video
          src={staticFile(DEMO_CLIP)}
          muted
          loop
          style={{ width: "100%", height: "100%", objectFit: "cover" }}
        />
      }
      to={
        <Video
          src={staticFile(DEMO_CLIP)}
          muted
          loop
          trimBefore={90}
          style={{
            width: "100%",
            height: "100%",
            objectFit: "cover",
            filter: "hue-rotate(150deg) saturate(1.3)",
          }}
        />
      }
    />
  </AbsoluteFill>
);

